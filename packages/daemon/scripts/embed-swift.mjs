// Embeds the Swift helpers into TypeScript modules so they ship inside the single-file CLI bundle.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'desktop');

const helpers = [
  { swift: 'spotlight-hud.swift', out: 'spotlight-source.generated.ts', name: 'SPOTLIGHT_SWIFT_SOURCE' },
  { swift: 'ax-helper.swift', out: 'ax-helper-source.generated.ts', name: 'AX_HELPER_SWIFT_SOURCE' },
];

for (const { swift, out, name } of helpers) {
  const source = readFileSync(join(root, swift), 'utf8');
  const text =
    `// Generated by scripts/embed-swift.mjs from ${swift}. Do not edit; run \`npm run build -w @remote-hands/daemon\`.\n` +
    `export const ${name}: string = ${JSON.stringify(source)};\n`;
  const target = join(root, out);
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {}
  if (current !== text) writeFileSync(target, text);
}

// The Windows HUD's C# sources, built on the person's PC by the compiler that ships with Windows.
{
  const dir = join(root, 'windows-hud');
  const files = ['HudLogic.cs', 'Hud.cs'];
  const sources = {};
  for (const file of files) {
    const text = readFileSync(join(dir, file), 'utf8');
    // The Windows compiler reads a file without a byte-order mark as ANSI: only plain ASCII is safe.
    // eslint-disable-next-line no-control-regex
    if (/[^\u0000-\u007f]/.test(text)) throw new Error(`${file} must be plain ASCII (use \\uXXXX escapes in strings)`);
    sources[file] = text;
  }
  const text =
    `// Generated by scripts/embed-swift.mjs from src/desktop/windows-hud/*.cs. Do not edit; run \`npm run build -w @remote-hands/daemon\`.\n` +
    `export const WINDOWS_HUD_SOURCES: Record<string, string> = ${JSON.stringify(sources)};\n`;
  const target = join(root, 'windows-hud-source.generated.ts');
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {}
  if (current !== text) writeFileSync(target, text);
}

// The HUD mascot's art, as base64, written next to the helper at run time (the helper loads the files from disk).
{
  const dir = join(root, '..', '..', 'assets', 'mascot');
  const assets = {};
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.png')).sort()) {
    assets[file] = readFileSync(join(dir, file)).toString('base64');
  }
  const text =
    `// Generated by scripts/embed-swift.mjs from assets/mascot/*.png. Do not edit; run \`npm run build -w @remote-hands/daemon\`.\n` +
    `export const MASCOT_ASSETS: Record<string, string> = ${JSON.stringify(assets)};\n`;
  const target = join(root, 'mascot-assets.generated.ts');
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {}
  if (current !== text) writeFileSync(target, text);
}
